JUDGE_SYSTEM_PROMPT = """You are an impartial, world-class Lead Business Intelligence Architect and Executive AI Evaluator acting as a rigorous LLM-as-a-Judge (G-Eval Framework).
Your mission is to strictly audit and grade the output generated by an autonomous BI Analyst Agent against the empirical Ground Truth statistics of the underlying dataset.
Be analytical, objective, and unforgiving of hallucinations, non-existent columns, or naive business recommendations."""


def extract_ground_truth(df: pd.DataFrame) -> Dict[str, Any]:
    """Extrait la vérité statistique exacte calculée par pandas."""
    n_rows, n_cols = df.shape
    missing_count = int(df.isnull().sum().sum())
    completeness = round(((df.size - missing_count) / max(df.size, 1)) * 100, 2)
    
    num_cols = list(df.select_dtypes(include=[np.number]).columns)
    cat_cols = list(df.select_dtypes(include=["object", "category", "bool"]).columns)
    
    num_stats = {}
    for col in num_cols[:15]:
        s = df[col].dropna()
        if len(s) > 0:
            num_stats[col] = {
                "mean": round(float(s.mean()), 2),
                "median": round(float(s.median()), 2),
                "min": round(float(s.min()), 2),
                "max": round(float(s.max()), 2),
                "std": round(float(s.std()), 2) if len(s) > 1 else 0.0
            }
            
    cat_stats = {}
    for col in cat_cols[:10]:
        s = df[col].dropna().astype(str)
        if len(s) > 0:
            cat_stats[col] = {
                "nunique": int(s.nunique()),
                "top_value": str(s.mode()[0]) if not s.empty else "N/A",
                "top_frequencies": s.value_counts().head(3).to_dict()
            }
            
    return {
        "total_rows": n_rows,
        "total_columns": n_cols,
        "completeness_pct": completeness,
        "all_column_names": list(df.columns),
        "numeric_columns": num_cols,
        "categorical_columns": cat_cols,
        "numeric_ground_truth_stats": num_stats,
        "categorical_ground_truth_stats": cat_stats
    }


def verify_charts_deterministically(charts: List[Dict[str, Any]], available_cols: List[str]) -> Dict[str, Any]:
    """Vérification déterministe Python des graphiques recommandés."""
    total_charts = len(charts)
    if total_charts == 0:
        return {"valid_charts_count": 0, "total_charts": 0, "valid_columns_pct": 0.0, "invalid_columns": []}
    
    invalid_columns = []
    valid_count = 0
    cols_set = set(c.lower() for c in available_cols)
    
    for c in charts:
        cx = c.get("column_x")
        cy = c.get("column_y")
        cx_ok = (cx is not None) and (str(cx).lower() in cols_set)
        cy_ok = (cy is None) or (str(cy).lower() in cols_set)
        
        if cx and str(cx).lower() not in cols_set:
            invalid_columns.append(cx)
        if cy and str(cy).lower() not in cols_set:
            invalid_columns.append(cy)
            
        if cx_ok and cy_ok:
            valid_count += 1
            
    return {
        "valid_charts_count": valid_count,
        "total_charts": total_charts,
        "valid_columns_pct": round((valid_count / total_charts) * 100, 1),
        "invalid_columns": list(set(invalid_columns))
    }


def evaluate_bi_analyst(dataset_path: Path, engine: str = "auto") -> Dict[str, Any]:
    print("=" * 80)
    print("⚖️  BIFLOW LLM-AS-A-JUDGE : ÉVALUATION COMPLÈTE DU BI ANALYST AGENT")
    print("=" * 80)
    
    if not dataset_path.exists():
        print(f"❌ Dataset introuvable : {dataset_path}")
        return {}
        
    print(f"📂 Dataset testé : {dataset_path.name}")
    df = pd.read_csv(dataset_path)
    print(f"📊 Dimensions     : {df.shape[0]} lignes × {df.shape[1]} colonnes")
    
    # ────────────────────────────────────────────────────────────────────────
    # ÉTAPE 1 : Calcul de la Vérité Terrain
    # ────────────────────────────────────────────────────────────────────────
    print("\n[ÉTAPE 1] 🔬 Calcul de la Vérité Terrain Statistique (Pandas)...")
    ground_truth = extract_ground_truth(df)
    print(f"  ✅ Complétude : {ground_truth['completeness_pct']}% | "
          f"{len(ground_truth['numeric_columns'])} colonnes numériques, "
          f"{len(ground_truth['categorical_columns'])} catégorielles.")
          
    # ────────────────────────────────────────────────────────────────────────
    # ÉTAPE 2 : Exécution de l'Agent BIAnalystAgent
    # ────────────────────────────────────────────────────────────────────────
    print(f"\n[ÉTAPE 2] 🤖 Exécution de l'Agent BIAnalyst (moteur={engine})...")
    agent = BIAnalystAgent(engine=engine)
    
    t0_agent = time.perf_counter()
    raw_response = agent.analyze(df, dataset_name=dataset_path.name)
    agent_duration = time.perf_counter() - t0_agent
    
    report_md, chart_config = agent.parse_response(raw_response)
    telemetry = agent.get_telemetry()
    
    kpis = chart_config.get("kpis", [])
    charts = chart_config.get("recommended_charts", [])
    
    print(f"  ✅ Analyse générée en {agent_duration:.2f}s !")
    print(f"  ⚡ Moteur utilisé : {telemetry.get('execution_mode')}")
    print(f"  🎯 KPIs extraits   : {len(kpis)}")
    print(f"  📈 Graphiques      : {len(charts)}")
    print(f"  📝 Longueur Rapport: {len(report_md)} caractères")
    
    # Vérification déterministe préliminaire
    chart_check = verify_charts_deterministically(charts, ground_truth["all_column_names"])
    
    # ────────────────────────────────────────────────────────────────────────
    # ÉTAPE 3 : Soumission du dossier au Juge LLM (Gemini)
    # ────────────────────────────────────────────────────────────────────────
    print(f"\n[ÉTAPE 3] ⚖️  Soumission au Juge Indépendant (Gemini 3.5 Flash)...")
    
    evaluation_dossier = {
        "dataset_name": dataset_path.name,
        "ground_truth": {
            "total_rows": ground_truth["total_rows"],
            "total_columns": ground_truth["total_columns"],
            "completeness_pct": ground_truth["completeness_pct"],
            "valid_column_names": ground_truth["all_column_names"],
            "sample_numeric_stats": ground_truth["numeric_ground_truth_stats"],
            "sample_categorical_stats": ground_truth["categorical_ground_truth_stats"]
        },
        "agent_output": {
            "execution_mode": telemetry.get("execution_mode"),
            "kpis_generated": kpis,
            "recommended_charts": charts,
            "executive_report_markdown": report_md
        },
        "deterministic_verification": {
            "charts_with_valid_columns_pct": chart_check["valid_columns_pct"],
            "hallucinated_column_names": chart_check["invalid_columns"]
        }
    }
    
    judge_prompt = f"""Evaluate the following BI Analyst Agent output against the empirical Ground Truth of the dataset.

DOSSIER SUBMITTED FOR EVALUATION:
```json
{json.dumps(evaluation_dossier, indent=2, ensure_ascii=False, default=str)}
```

EVALUATION RUBRICS (Score each from 1 to 5):
1. factual_grounding_and_kpis: Are the generated KPIs and numbers in the report faithful to the ground truth statistics? Are there hallucinations or invented data? (5 = Zero hallucination, perfectly aligned with ground truth; 1 = Completely fabricated numbers).
2. chart_relevance_and_validity: Do the recommended charts use valid column names that actually exist in the dataset? Are the chosen chart types (pie, bar, histogram, scatter, box) appropriate for the data types? (5 = 100% valid existing columns with ideal chart mappings; 1 = Uses imaginary columns or nonsensical visualization choices).
3. analytical_depth_and_trends: Does the executive report meaningfully uncover patterns, segmentations, or correlations present in the data? (5 = Executive-grade business intelligence insights; 1 = Generic filler text).
4. strategic_actionability: Are the recommendations concrete, prioritized, realistic, and directly actionable for business decision-makers? (5 = High ROI strategic decisions; 1 = Trivial or irrelevant suggestions).
5. schema_and_structure_compliance: Did the agent respect the required structure (Executive Summary, Key KPIs, Trends, Anomalies, Strategic Recommendations) and provide a clean, parseable JSON block for charts & KPIs? (5 = Flawless formatting and parsing; 1 = Broken format or missing sections).

Provide your evaluation in STRICT JSON format:
{{
  "judge_model": "Google Gemini 3.5 Flash",
  "evaluated_engine": "{telemetry.get('execution_mode')}",
  "rubrics": {{
    "factual_grounding_and_kpis": {{"score_1_to_5": <int 1-5>, "justification": "<string>"}},
    "chart_relevance_and_validity": {{"score_1_to_5": <int 1-5>, "justification": "<string>"}},
    "analytical_depth_and_trends": {{"score_1_to_5": <int 1-5>, "justification": "<string>"}},
    "strategic_actionability": {{"score_1_to_5": <int 1-5>, "justification": "<string>"}},
    "schema_and_structure_compliance": {{"score_1_to_5": <int 1-5>, "justification": "<string>"}}
  }},
  "overall_score_pct": <float between 0 and 100>,
  "verdict": "<EXCELLENT | GOOD | ACCEPTABLE | DEFICIENT>",
  "strengths": ["<string>", "<string>"],
  "weaknesses": ["<string>", "<string>"],
  "judge_executive_summary": "<concise summary of the evaluation for academic or executive presentation>"
}}"""

    t0_judge = time.perf_counter()
    judge_response = {}

    # Tentative 1 : Gemini
    try:
        from agents.llm_client import LLMClient as UnifiedLLMClient
        judge_client = UnifiedLLMClient(provider="gemini", model_name="models/gemini-3.5-flash")
        judge_response = judge_client.generate_json(judge_prompt, system_prompt=JUDGE_SYSTEM_PROMPT)
    except Exception as e:
        print(f"  ⚠️ Tentative Juge Gemini a échoué: {e}")

    # Tentative 2 : Fallback Groq (si Gemini indisponible ou JSON vide)
    if not judge_response or "rubrics" not in judge_response:
        print("  🔄 Bascule vers le Juge Groq (openai/gpt-oss-120b / gpt-oss-20b)...")
        groq_api_key = os.environ.get("GROQ_API_KEY")
        if groq_api_key:
            try:
                from groq import Groq
                groq_c = Groq(api_key=groq_api_key)
                for gm in ["openai/gpt-oss-120b", "openai/gpt-oss-20b", "qwen/qwen3.8-27b"]:
                    try:
                        g_resp = groq_c.chat.completions.create(
                            messages=[
                                {"role": "system", "content": JUDGE_SYSTEM_PROMPT},
                                {"role": "user", "content": judge_prompt}
                            ],
                            model=gm,
                            temperature=0.1,
                            max_tokens=3000
                        )
                        raw_j = g_resp.choices[0].message.content
                        if raw_j:
                            judge_response = UnifiedLLMClient()._extract_json(raw_j)
                            if judge_response and "rubrics" in judge_response:
                                judge_response["judge_model"] = f"Groq ({gm})"
                                break
                    except Exception as ge:
                        continue
            except Exception as e:
                print(f"  ⚠️ Tentative Juge Groq a échoué: {e}")

    judge_duration = time.perf_counter() - t0_judge
    
    if not judge_response or "rubrics" not in judge_response:
        print("⚠️ Le Juge n'a pas retourné de JSON valide. Réponse brute :")
        print(judge_response)
        return {}
        
    print(f"  ✅ Délibération du Juge terminée en {judge_duration:.2f} secondes !\n")
    
    # ────────────────────────────────────────────────────────────────────────
    # ÉTAPE 4 : Affichage du Verdict
    # ────────────────────────────────────────────────────────────────────────
    print("=" * 80)
    print("🏆 VERDICT DU JUGE LLM-AS-A-JUDGE (G-EVAL)")
    print("=" * 80)
    
    rubrics = judge_response["rubrics"]
    rubric_names_fr = {
        "factual_grounding_and_kpis": "Exactitude des KPIs & Ancrage Réel",
        "chart_relevance_and_validity": "Pertinence & Validité des Graphiques",
        "analytical_depth_and_trends": "Profondeur d'Analyse & Tendances",
        "strategic_actionability": "Actionnabilité Stratégique",
        "schema_and_structure_compliance": "Conformité du Format & Schéma JSON"
    }
    
    for rubric_key, details in rubrics.items():
        score = details.get("score_1_to_5", 0)
        justif = details.get("justification", "")
        nom = rubric_names_fr.get(rubric_key, rubric_key)
        stars = "⭐" * int(score) + "☆" * (5 - int(score))
        print(f"\n📌 {nom} : {score}/5 {stars}")
        print(f"   💬 Justification : {justif}")
        
    overall = judge_response.get("overall_score_pct", 0.0)
    verdict = judge_response.get("verdict", "UNKNOWN")
    print("\n" + "-" * 80)
    print(f"🎯 SCORE GLOBAL NORMALISÉ : {overall}%")
    print(f"🎖️ VERDICT DU JUGE         : {verdict}")
    print("-" * 80)
    
    strengths = judge_response.get("strengths", [])
    if strengths:
        print("\n✨ Points Forts :")
        for s in strengths:
            print(f"  • {s}")
            
    weaknesses = judge_response.get("weaknesses", [])
    if weaknesses:
        print("\n⚠️ Points d'Amélioration :")
        for w in weaknesses:
            print(f"  • {w}")
            
    summary = judge_response.get("judge_executive_summary", "")
    print(f"\n📝 Synthèse du Juge :\n\"{summary}\"\n")
    
    # Sauvegarde du rapport
    reports_dir = PROJECT_ROOT / "data" / "reports"
    reports_dir.mkdir(parents=True, exist_ok=True)
    report_file = reports_dir / f"llm_judge_bi_analyst_{dataset_path.stem}.json"
    
    final_output = {
        "dataset": dataset_path.name,
        "evaluation_timestamp": time.strftime("%Y-%m-%d %H:%M:%S"),
        "agent_telemetry": telemetry,
        "deterministic_verification": chart_check,
        "judge_evaluation": judge_response
    }
    
    with open(report_file, "w", encoding="utf-8") as f:
        json.dump(final_output, f, indent=2, ensure_ascii=False)
        
    print(f"📁 Rapport d'évaluation officiel sauvegardé dans :\n   {report_file}")
    return final_output


