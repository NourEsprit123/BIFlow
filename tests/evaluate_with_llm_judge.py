"""
Évaluation en direct Cross-Vendor : LLM-as-a-Judge (Framework G-Eval)
1. Candidat : DataEngineeringAgent (alimenté en direct par l'API Gemini 3.5 Flash)
   -> Analyse le dataset, produit son raisonnement en direct et déclenche la sandbox.
2. Juge : Qwen 2.5 7B (tournant en local sur GPU RTX 4050 via Ollama)
   -> Récupère le raisonnement produit en direct par Gemini et le note selon les 5 critères G-Eval.
"""

import os
import sys
import json
import time
from pathlib import Path
import pandas as pd

# Fix Windows console encoding
if hasattr(sys.stdout, "reconfigure"):
    sys.stdout.reconfigure(encoding="utf-8")

PROJECT_ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(PROJECT_ROOT))

from agents.llm_client import LLMClient
from agents.data_engineering_agent import DataEngineeringAgent


JUDGE_SYSTEM_PROMPT = """You are an impartial, world-class Senior Data Architect and Lead AI Evaluator acting as an LLM Judge (G-Eval Framework).
Your mission is to rigorously evaluate an autonomous Data Engineering Agent's live audit report on a dataset.
Be strict, objective, and analytical. Base your ratings solely on empirical evidence."""


def run_live_cross_evaluation():
    print("=" * 80)
    print("🚀 ÉVALUATION EN DIRECT : GEMINI (AGENT) JUGÉ PAR QWEN 2.5 7B (JUGE LOCAL)")
    print("=" * 80)

    dataset_path = PROJECT_ROOT / "data" / "raw" / "benchmark_eval_dataset.csv"
    if not dataset_path.exists():
        print(f"❌ Dataset étalon introuvable : {dataset_path}")
        return

    # ────────────────────────────────────────────────────────────────────────
    # ÉTAPE 1 : L'Agent appelle Gemini en direct pour analyser le dataset
    # ────────────────────────────────────────────────────────────────────────
    print(f"\n[ÉTAPE 1] Lancement de l'audit en direct par l'Agent 1 (API Google Gemini)...")
    gemini_client = LLMClient(provider="gemini", model_name="models/gemini-3.5-flash-lite")
    agent = DataEngineeringAgent(llm_client=gemini_client)

    t0_agent = time.perf_counter()
    audit_result = agent.run_audit(str(dataset_path))
    agent_duration = time.perf_counter() - t0_agent
    print(f"  ✅ Audit Gemini terminé en {agent_duration:.2f} secondes !")

    profiling_report = audit_result.get("profiling_report", {})
    health = audit_result.get("health", {})
    profile = audit_result.get("profile", {})

    # Extraire les raisonnements réels générés par Gemini pour chaque colonne
    col_profiles = profiling_report.get("column_profiles", {})
    gemini_reasoning_summary = {}
    for col, data in col_profiles.items():
        gemini_reasoning_summary[col] = {
            "inferred_role": data.get("inferred_role"),
            "dtype": data.get("dtype"),
            "severity": data.get("severity"),
            "gemini_agent_reasoning": data.get("agent_reasoning"),
            "business_interpretation": data.get("business_interpretation"),
            "recommended_imputation": data.get("imputation_strategy"),
            "sandbox_triggered": data.get("sandbox_triggered"),
            "sandbox_result": data.get("sandbox_result")
        }

    # Dossier d'évaluation complet soumis au Juge
    live_payload = {
        "dataset_name": dataset_path.name,
        "rows": profiling_report.get("dataset_level", {}).get("total_rows"),
        "columns_analyzed": list(col_profiles.keys()),
        "data_profiler_output": {
            "overall_health_score": health.get("overall_health_score"),
            "completeness": health.get("completeness"),
            "validity": health.get("validity"),
            "uniqueness": health.get("uniqueness")
        },
        "gemini_agent_live_reasoning": gemini_reasoning_summary,
        "etl_hints_generated": profiling_report.get("etl_hints", {}),
        "cleaning_priority_order": profiling_report.get("recommended_cleaning_order", [])
    }

    print(f"  📊 Rapport généré : {len(gemini_reasoning_summary)} colonnes analysées par Gemini.")

    # ────────────────────────────────────────────────────────────────────────
    # ÉTAPE 2 : Qwen 2.5 7B (en local) juge en direct la production de Gemini
    # ────────────────────────────────────────────────────────────────────────
    print(f"\n[ÉTAPE 2] Soumission du raisonnement de Gemini au Juge Qwen 2.5 7B (Local RTX 4050)...")

    judge_prompt = f"""Evaluate the following Data Engineering Agent audit work (generated by Gemini API) using the 5 G-Eval Rubrics below.
Provide a rigorous score from 1 to 5 for each rubric, accompanied by an explicit justification, then calculate the Normalized Final Score (0-100%).

DATA ENGINEERING AGENT LIVE AUDIT PAYLOAD:
```json
{json.dumps(live_payload, indent=2, ensure_ascii=False, default=str)}
```

EVALUATION RUBRICS (Score 1 to 5 each):
1. Factual Grounding: Does Gemini strictly ground its reasoning in the calculated statistics? Are there any hallucinations or invented metrics? (5 = Perfect adherence, 1 = Severe hallucinations).
2. Diagnostic & Causal Relevance: Does Gemini properly identify the business root causes and risks (e.g. negative charges, join key integrity, currency symbols)? (5 = Deep expert insight, 1 = Naive/irrelevant).
3. Sandbox Check Appropriateness: Was the custom Python check well-targeted, syntactically clean, safe, and did it isolate the problem effectively? (5 = Production-grade unit test, 1 = Broken/dangerous code).
4. Severity Calibration: Are the risk levels (HIGH, MEDIUM, LOW) mathematically and operationally justified? (5 = Perfectly calibrated, 1 = Mislabeled risks).
5. ETL Actionability: Are the recommended cleaning actions (median imputation, casting, drop policies) statistically sound for downstream BI and ML? (5 = Industry best practice, 1 = Harmful transformations).

Return STRICT JSON format:
{{
  "evaluator": "Qwen 2.5 7B Local Independent Judge",
  "evaluated_agent_llm": "Google Gemini 3.5 Flash",
  "rubrics": {{
    "factual_grounding": {{"score_1_to_5": <int>, "justification": "<string>"}},
    "diagnostic_relevance": {{"score_1_to_5": <int>, "justification": "<string>"}},
    "sandbox_appropriateness": {{"score_1_to_5": <int>, "justification": "<string>"}},
    "severity_calibration": {{"score_1_to_5": <int>, "justification": "<string>"}},
    "etl_actionability": {{"score_1_to_5": <int>, "justification": "<string>"}}
  }},
  "overall_score_pct": <float>,
  "verdict": "<EXCELLENT | GOOD | ACCEPTABLE | DEFICIENT>",
  "executive_summary_for_jury": "<string>"
}}"""

    judge_client = LLMClient(provider="ollama", model_name="qwen2.5:7b")
    t0_judge = time.perf_counter()
    judge_response = judge_client.generate_json(judge_prompt, system_prompt=JUDGE_SYSTEM_PROMPT)
    judge_duration = time.perf_counter() - t0_judge

    if not judge_response or "rubrics" not in judge_response:
        print("⚠️ Qwen n'a pas retourné de JSON valide. Réponse brute:")
        print(judge_response)
        return

    print(f"  ✅ Jugement de Qwen 2.5 7B rendu en {judge_duration:.2f} secondes !\n")

    # ────────────────────────────────────────────────────────────────────────
    # ÉTAPE 3 : Affichage des Résultats
    # ────────────────────────────────────────────────────────────────────────
    print("=" * 80)
    print("📋 RÉSULTATS DU JURY CROISÉ : QWEN 2.5 7B JUGE GEMINI EN DIRECT")
    print("=" * 80)

    rubrics = judge_response["rubrics"]
    for rubric_name, details in rubrics.items():
        score = details.get("score_1_to_5")
        justif = details.get("justification")
        name_fr = rubric_name.replace("_", " ").title()
        print(f"\n🔹 {name_fr} : {score} / 5 ⭐")
        print(f"   Justification : {justif}")

    overall = judge_response.get("overall_score_pct", 0.0)
    verdict = judge_response.get("verdict", "INCONNU")
    summary = judge_response.get("executive_summary_for_jury", "")

    print("\n" + "-" * 80)
    print(f"🏆 SCORE GLOBAL NORMALISÉ (Qwen juge Gemini) : {overall}%")
    print(f"🎖️ VERDICT DU JUGE                          : {verdict}")
    print("-" * 80)
    print(f"\n📝 Synthèse rédigée par Qwen pour le Jury de Soutenance :\n\"{summary}\"\n")

    # Sauvegarder le rapport officiel
    report_file = PROJECT_ROOT / "data" / "reports" / "live_cross_llm_judge_report.json"
    with open(report_file, "w", encoding="utf-8") as f:
        json.dump(judge_response, f, indent=2, ensure_ascii=False)

    print(f"📁 Rapport officiel sauvegardé dans : {report_file}")


if __name__ == "__main__":
    run_live_cross_evaluation()
