def test_profiling_recovers_column_omitted_from_llm_batch(tmp_path, monkeypatch):
    source = tmp_path / "raw" / "incomplete_batch.csv"
    source.parent.mkdir()
    column_names = [f"field_{index}" for index in range(6)]
    pd.DataFrame({name: [1, 2, 3] for name in column_names}).to_csv(
        source,
        index=False,
    )
    monkeypatch.chdir(tmp_path)

    class OmitThenCompleteLLMClient:
        provider = "test"

        def __init__(self):
            self.calls = []

        def generate_json(self, prompt, system_prompt=None, max_output_tokens=None):
            self.calls.append((prompt, system_prompt, max_output_tokens))
            if "completion request for one missing column" in prompt:
                missing_name = next(
                    name for name in column_names
                    if f'"{name}"' in prompt
                )
                return {
                    "columns": [{
                        "name": missing_name,
                        "type": "numeric",
                        "role": "measure",
                        "insight": f"LLM profile for {missing_name}.",
                    }]
                }

            batch_columns = [
                name for name in column_names
                if f'"{name}"' in prompt
            ]
            if len(self.calls) == 1:
                batch_columns = batch_columns[:-1]
            response = {
                "columns": llm_profile(batch_columns)["columns"],
            }
            if len(self.calls) == 1:
                response["profile_summary"] = "Summary across the dataset."
            return response

    llm = OmitThenCompleteLLMClient()
    result = DataEngineeringAgent(llm_client=llm).run_workflow(
        str(source),
        "profiling",
    )

    assert result["status"] == "success"
    assert [item["name"] for item in result["llm_analysis"]["columns"]] == column_names
    assert len(llm.calls) == 3
    assert llm.calls[-1][2] == 200
    assert "field_2" in llm.calls[-1][0]


